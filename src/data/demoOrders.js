export function loadStoredOrders() {
  try {
    const raw = localStorage.getItem(ORDERS_STORAGE_KEY)
    if (raw) {
      const parsed = JSON.parse(raw)
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Ensure any newly added initial orders (e.g., ORD-9021) are present
        const existingIds = new Set(
          parsed.map((o) => String(o.id || o.order_number).replace('#', '').toLowerCase())
        )
        const missing = initialOrders.filter(
          (io) => !existingIds.has(String(io.id || io.order_number).replace('#', '').toLowerCase())
        )
        if (missing.length > 0) {
          const merged = [...missing, ...parsed]
          saveStoredOrders(merged)
          return merged
        }
        return parsed
      }
    }
  } catch (err) {
    console.error('Failed to load orders from localStorage:', err)
  }
  saveStoredOrders(initialOrders)
  return initialOrders
}

export function saveStoredOrders(orders) {
  try {
    localStorage.setItem(ORDERS_STORAGE_KEY, JSON.stringify(orders))
    window.dispatchEvent(new CustomEvent('orders-data-updated', { detail: { orders } }))
  } catch (err) {
    console.error('Failed to save orders to localStorage:', err)
  }
}

export function getOrderById(id) {
  if (!id) return null
  const cleanId = String(id).replace('#', '').toLowerCase().trim()
  const orders = loadStoredOrders()

  let match = orders.find((o) => {
    const oId = String(o.id || '').replace('#', '').toLowerCase().trim()
    const oNum = String(o.order_number || '').replace('#', '').toLowerCase().trim()
    return oId === cleanId || oNum === cleanId || o.id === id || o.order_number === id
  })

  if (!match) {
    match = initialOrders.find((o) => {
      const oId = String(o.id || '').replace('#', '').toLowerCase().trim()
      const oNum = String(o.order_number || '').replace('#', '').toLowerCase().trim()
      return oId === cleanId || oNum === cleanId || o.id === id || o.order_number === id
    })
  }

  return match || null
}

export function updateOrderStatus(orderId, newStatus, { reason = '', notes = '', confirmationCode = '' } = {}) {
  const orders = loadStoredOrders()
  const timeNow = new Date().toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit' })
  const isoNow = new Date().toISOString()

  const updatedList = orders.map((order) => {
    if (order.id !== orderId && order.order_number !== orderId) {
      return order
    }

    const currentTracking = order.order_status_tracking || {}
    const updatedTracking = {
      ...currentTracking,
      current_status: newStatus,
    }

    if (newStatus === 'PREPARING') {
      updatedTracking.order_confirmed_at = updatedTracking.order_confirmed_at || timeNow
      updatedTracking.preparing_started_at = timeNow
    } else if (newStatus === 'OUT_FOR_DELIVERY') {
      updatedTracking.ready_for_pickup_at = updatedTracking.ready_for_pickup_at || timeNow
      updatedTracking.order_picked_up_at = updatedTracking.order_picked_up_at || timeNow
      updatedTracking.rider_en_route_to_customer_at = timeNow
    } else if (newStatus === 'DELIVERED') {
      updatedTracking.rider_arrived_at_delivery_at = updatedTracking.rider_arrived_at_delivery_at || timeNow
      updatedTracking.order_delivered_at = timeNow
    } else if (newStatus === 'CANCELLED') {
      updatedTracking.cancelled_at = timeNow
      updatedTracking.cancellation_reason = reason || 'Cancelled by operations administrator.'
    }

    return {
      ...order,
      status: newStatus,
      delivery_approved_at: newStatus === 'DELIVERED' ? isoNow : order.delivery_approved_at,
      delivery_confirmation_code: confirmationCode || order.delivery_confirmation_code,
      delivery_notes: notes ? `${order.delivery_notes ? order.delivery_notes + ' • ' : ''}${notes}` : order.delivery_notes,
      order_status_tracking: updatedTracking,
    }
  })

  saveStoredOrders(updatedList)
  return updatedList.find((o) => o.id === orderId || o.order_number === orderId)
}

